import 'package:flutter/material.dart';

import '../../../../core/theme/app_theme.dart';
import '../widgets/guide_pieces.dart';

/// The in-app twin of the published web user guide — same content, reached
/// without leaving the app so a doctor or nurse can look something up mid-
/// task instead of hunting for a link elsewhere. Reachable from the
/// dashboard header (everyone) and from Admin (admins).
class HelpGuidePage extends StatelessWidget {
  const HelpGuidePage({super.key});

  @override
  Widget build(BuildContext context) {
    final sections = _buildSections();
    return Scaffold(
      appBar: AppBar(title: const Text('دليل الاستخدام')),
      body: ResponsiveBody(
        maxWidth: 820,
        child: ListView.separated(
          padding: const EdgeInsets.all(AppSpacing.lg),
          itemCount: sections.length,
          separatorBuilder: (_, _) => const SizedBox(height: AppSpacing.sm),
          itemBuilder: (context, index) => _GuideSectionCard(
            data: sections[index],
            initiallyExpanded: index == 0,
          ),
        ),
      ),
    );
  }
}

class _GuideSectionData {
  const _GuideSectionData({
    required this.icon,
    required this.title,
    required this.subtitle,
    required this.body,
  });

  final IconData icon;
  final String title;
  final String subtitle;
  final List<Widget> body;
}

class _GuideSectionCard extends StatelessWidget {
  const _GuideSectionCard({
    required this.data,
    required this.initiallyExpanded,
  });

  final _GuideSectionData data;
  final bool initiallyExpanded;

  @override
  Widget build(BuildContext context) {
    return Container(
      decoration: BoxDecoration(
        color: Colors.white,
        borderRadius: BorderRadius.circular(20),
        boxShadow: AppShadows.card,
      ),
      clipBehavior: Clip.antiAlias,
      child: Theme(
        data: Theme.of(context).copyWith(dividerColor: Colors.transparent),
        child: ExpansionTile(
          initiallyExpanded: initiallyExpanded,
          tilePadding: const EdgeInsets.symmetric(
            horizontal: AppSpacing.lg,
            vertical: 6,
          ),
          childrenPadding: const EdgeInsets.fromLTRB(
            AppSpacing.lg,
            0,
            AppSpacing.lg,
            AppSpacing.lg,
          ),
          leading: Container(
            padding: const EdgeInsets.all(8),
            decoration: BoxDecoration(
              color: AppColors.aqua.withValues(alpha: 0.1),
              borderRadius: BorderRadius.circular(10),
            ),
            child: Icon(data.icon, color: AppColors.aqua, size: 18),
          ),
          title: Text(
            data.title,
            style: const TextStyle(fontWeight: FontWeight.w700, fontSize: 14),
          ),
          subtitle: Text(
            data.subtitle,
            style: const TextStyle(fontSize: 11.5, color: AppColors.inkSoft),
          ),
          children: [
            Align(
              alignment: Alignment.centerRight,
              child: Column(
                crossAxisAlignment: CrossAxisAlignment.stretch,
                children: data.body,
              ),
            ),
          ],
        ),
      ),
    );
  }
}

